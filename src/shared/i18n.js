/**
 * Текущий язык интерфейса — без DOM и без настроек.
 *
 * Язык хранится в настройках тренажёра (P.lang), но решатели и форматирование
 * не должны зависеть от настроек: тогда их можно проверять в Node. Поэтому
 * тренажёр один раз сообщает, откуда брать язык, а остальной код спрашивает lang().
 *
 *   langFrom(() => P.lang);   // в тренажёре, сразу после загрузки настроек
 *   langFrom(() => 'en');     // в тесте
 */

/** @typedef {'ru' | 'en'} Lang */

/** @type {() => string} */
let source = () => 'ru';

/** Задаёт источник текущего языка. @param {() => string} fn */
export function langFrom(fn) {
  source = fn;
}

/** Текущий язык: 'ru' или 'en' (всё, кроме 'en', считается русским). @returns {Lang} */
export function lang() {
  return source() === 'en' ? 'en' : 'ru';
}
